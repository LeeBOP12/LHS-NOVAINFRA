function getServiceGroupIconKey(title) {
  const normalizedTitle = title.toLowerCase().normalize("NFD").replace(/[\u0300-\u036f]/g, "");

  if (normalizedTitle.includes("topografia")) return "survey";
  if (normalizedTitle.includes("consultoria")) return "consulting";
  if (normalizedTitle.includes("bim")) return "bim";
  if (normalizedTitle.includes("gestion") || normalizedTitle.includes("epcm") || normalizedTitle.includes("pmc")) return "management";
  if (normalizedTitle.includes("diseno")) return "design";
  if (normalizedTitle.includes("construccion")) return "construction";
  if (normalizedTitle.includes("infraestructura")) return "infrastructure";
  if (normalizedTitle.includes("mineria") || normalizedTitle.includes("energia") || normalizedTitle.includes("industria") || normalizedTitle.includes("control")) return "industry";
  if (normalizedTitle.includes("mantenimiento") || normalizedTitle.includes("suministro") || normalizedTitle.includes("equipamiento")) return "maintenance";
  if (normalizedTitle.includes("ambiental") || normalizedTitle.includes("sostenibilidad")) return "environmental";
  if (normalizedTitle.includes("residuos")) return "waste";

  return "default";
}

function createServiceGroupIcon(title, className) {
  const icon = document.createElement("span");
  icon.className = className;
  icon.setAttribute("aria-hidden", "true");
  icon.innerHTML = serviceGroupIcons[getServiceGroupIconKey(title)] || serviceGroupIcons.default;
  return icon;
}

const serviceCards = Array.from(document.querySelectorAll("[data-service]"));
const serviceModal = document.querySelector(".service-modal");
const serviceModalCloseButtons = document.querySelectorAll("[data-close-service]");
const serviceDetailNumber = document.querySelector("#service-detail-number");
const serviceDetailTitle = document.querySelector("#service-detail-title");
const serviceDetailText = document.querySelector("#service-detail-text");
const serviceDetailList = document.querySelector("#service-detail-list");
let activeServiceIndex = -1;
let lastServiceTrigger;

function updateServiceDetail(serviceKey, index) {
  const detail = serviceDetails[serviceKey];
  if (!detail || !serviceModal || !serviceDetailNumber || !serviceDetailTitle || !serviceDetailText || !serviceDetailList) return;

  activeServiceIndex = index;
  lastServiceTrigger = serviceCards[activeServiceIndex];
  serviceCards.forEach((card, cardIndex) => {
    const isActive = cardIndex === activeServiceIndex;
    card.classList.toggle("is-active", isActive);
    card.setAttribute("aria-expanded", String(isActive));
  });

  serviceDetailNumber.textContent = detail.number;
  serviceDetailTitle.textContent = detail.title;
  serviceDetailText.textContent = detail.text;
  serviceDetailList.innerHTML = "";

  detail.groups.forEach((group) => {
    const groupCard = document.createElement("article");
    groupCard.className = "service-detail-group";
    groupCard.appendChild(createServiceGroupIcon(group.title, "service-group-watermark"));

    const groupHeader = document.createElement("div");
    groupHeader.className = "service-group-title";
    groupHeader.appendChild(createServiceGroupIcon(group.title, "service-group-icon"));

    const groupTitle = document.createElement("h4");
    groupTitle.textContent = group.title;
    groupHeader.appendChild(groupTitle);
    groupCard.appendChild(groupHeader);

    const groupList = document.createElement("ul");
    group.items.forEach((item) => {
      const listItem = document.createElement("li");
      listItem.textContent = item;
      groupList.appendChild(listItem);
    });

    groupCard.appendChild(groupList);
    serviceDetailList.appendChild(groupCard);
  });

  serviceModal.hidden = false;
  serviceModal.setAttribute("aria-hidden", "false");
  document.body.classList.add("modal-open");
  serviceModal.classList.remove("is-open");
  requestAnimationFrame(() => serviceModal.classList.add("is-open"));
  serviceModal.querySelector(".service-modal-close")?.focus();
}

function closeServiceDetail() {
  if (!serviceModal) return;

  serviceModal.hidden = true;
  serviceModal.setAttribute("aria-hidden", "true");
  serviceModal.classList.remove("is-open");
  document.body.classList.remove("modal-open");
  activeServiceIndex = -1;

  serviceCards.forEach((card) => {
    card.classList.remove("is-active");
    card.setAttribute("aria-expanded", "false");
  });

  lastServiceTrigger?.focus();
}

serviceCards.forEach((card, index) => {
  card.addEventListener("click", () => updateServiceDetail(card.dataset.service, index));
  card.addEventListener("keydown", (event) => {
    if (event.key === "Enter" || event.key === " ") {
      event.preventDefault();
      updateServiceDetail(card.dataset.service, index);
    }
  });
});

serviceModalCloseButtons.forEach((button) => {
  button.addEventListener("click", closeServiceDetail);
});

serviceModal?.querySelector(".button")?.addEventListener("click", closeServiceDetail);

document.addEventListener("keydown", (event) => {
  if (event.key === "Escape" && serviceModal && !serviceModal.hidden) {
    closeServiceDetail();
  }
});
